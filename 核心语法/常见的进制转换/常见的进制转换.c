#include <stdio.h>
int main() {
    // 在C语言的二进制输出
    int a= 0b10;
    printf("%d\n",a);
    // C语言的十进制输出
    int b=10;
    printf("%d\n",b);
    // C语言的八进制输出
    int c=011;
    printf("%d\n",c);
    //C语言的十六进制输出
    int d=0xa;
    printf("%d\n",d);
    return 0;
}