#include <stdio.h>

/*
 * 每组小毛线团长度 18、21、25，三种共 64 米；
 * 一根 60 米的大毛线团最多裁出若干件。最优装法为：
 *   18+21+21 = 60  （装 3 件）
 *   18+18+25 = 61 超限，故 18+18+21 = 57 也是装 3 件
 *   25+25 = 50        （装 2 件）
 * 结论（n = 1..6 时）：n 组共需 n 根 18、n 根 21、n 根 25，
 * 每 6 组（6×64 = 384 米）恰好可用 6 + 1 = 7 根装完，
 * 由此得到公式：ans = n + (n - 1) / 6 + 1。
 */
int main(void) {
    long long n;
    scanf("%lld", &n);
    printf("%lld\n", n + (n - 1) / 6 + 1);
    return 0;
}