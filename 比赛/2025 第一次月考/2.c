/*扑克牌

小A和小B一人抽一张扑克牌，比谁的点数更大（这副扑克的大小王被小C搞丢了，其中A用1替代，J、Q、K分别用11、12、13替代）
输入格式:
两个整数，第一个整数代表小A抽到的扑克牌的点数，第二个整数代表小B抽到的扑克牌的点数。

输出格式:
一个字符（如果是小A赢则输出“A”，如果是小B赢则输出“B”，平局就输出“=”）。*/
#include <stdio.h>

int main() {
    int a, b;
    scanf("%d%d", &a, &b);
    if (a > b)printf("A");
    if (a < b)printf("B");
    if (a == b)printf("=");
    return 0;
}
